// Parse a list of integer ids from a string (any non-digit is a separator).
std::unordered_set<int> parse_id_list(const std::string& s) {
    std::unordered_set<int> out;
    std::string num;
    for (char c : s) {
        if (c >= '0' && c <= '9') { num += c; continue; }
        if (!num.empty()) { out.insert(std::atoi(num.c_str())); num.clear(); }
    }
    if (!num.empty()) out.insert(std::atoi(num.c_str()));
    return out;
}

size_t load_names() {
    g_names.clear();
    g_weapon_names.clear();
    // Baseline: the Paramdex names embedded at build time.
    parse_names_blob(kSpEffectNamesTxt, kSpEffectNamesTxtLen, g_names, false);
    parse_names_blob(kWeaponNamesTxt, kWeaponNamesTxtLen, g_weapon_names, false);
    // Optional overlay: a SpEffectParam.txt next to the DLL overrides/extends
    // the embedded list (overhaul mods' custom ids).
    std::ifstream f(names_path(), std::ios::binary);
    if (f) {
        const std::string blob((std::istreambuf_iterator<char>(f)),
                               std::istreambuf_iterator<char>());
        parse_names_blob(reinterpret_cast<const unsigned char*>(blob.data()),
                         blob.size(), g_names, true);
        flog("names: %zu SpEffect + %zu weapon names embedded, plus "
             "SpEffectParam.txt overrides next to the DLL",
             g_names.size(), g_weapon_names.size());
    } else {
        flog("names: %zu SpEffect + %zu weapon names embedded (Paramdex)",
             g_names.size(), g_weapon_names.size());
    }
    return g_names.size();
}

std::string named(int id) {
    const auto it = g_names.find(id);
    return it == g_names.end() ? std::to_string(id)
                               : std::to_string(id) + ":" + it->second;
}

std::string named_weapon(int id) {
    char buf[192];
    auto it = g_weapon_names.find(id);
    if (it != g_weapon_names.end()) {
        std::snprintf(buf, sizeof(buf), "%s (%d)", it->second.c_str(), id);
        return buf;
    }
    // Upgrade rows are base+level (base ids are multiples of 100); Paramdex
    // only names the base row.
    const int level = id % 100;
    it = g_weapon_names.find(id - level);
    if (it != g_weapon_names.end()) {
        std::snprintf(buf, sizeof(buf), "%s +%d (%d)", it->second.c_str(), level, id);
        return buf;
    }
    std::snprintf(buf, sizeof(buf), "#%d", id);
    return buf;
}

std::string join_ids(const std::vector<int>& ids) {
    std::string s;
    for (int id : ids) { s += named(id); s += ' '; }
    return s;
}

void load_config() {
    Ini ini;
    const bool loaded = ini.load(config_path());
    g_debug            = ini.get_bool("general", "debug_console",
                                      schema_def_bool("general", "debug_console"));
    g_log_effects      = ini.get_bool("general", "log_effects",
                                      schema_def_bool("general", "log_effects"));
    g_log_untracked    = ini.get_bool("general", "log_untracked",
                                      schema_def_bool("general", "log_untracked"));
    g_keep_fast_travel = ini.get_bool("persistence", "keep_after_fast_travel",
                                      schema_def_bool("persistence", "keep_after_fast_travel"));
    g_keep_death       = ini.get_bool("persistence", "keep_after_death",
                                      schema_def_bool("persistence", "keep_after_death"));
    g_persist_physick  = ini.get_bool("persistence", "persist_physick_tears",
                                      schema_def_bool("persistence", "persist_physick_tears"));
    g_weapon_memory    = ini.get_bool("weapon_memory", "remember_per_weapon",
                                      schema_def_bool("weapon_memory", "remember_per_weapon"));
    g_session_persist  = ini.get_bool("session", "remember_across_sessions",
                                      schema_def_bool("session", "remember_across_sessions"));
    // always_persist is hard-coded (g_always_persist); reapply delay is hard-coded
    // (kReapplyDelayMs). restore_remaining_time / restore_buff_power are core
    // behavior now (always on, no longer options).
    g_force_persist = parse_id_list(ini.get_string("persistence", "force_persist_ids", ""));
    g_never_persist = parse_id_list(ini.get_string("persistence", "never_persist_ids", ""));
    if (g_debug) { AllocConsole(); FILE* o=nullptr; freopen_s(&o, "CONOUT$", "w", stdout); }
    flog(loaded ? "config loaded from PersistentBuffs.ini"
                : "[WARN] .ini not found; using defaults");
    heal_config(ini, loaded);
    load_names();
    flog("settings:\n"
         "keep_after_fast_travel   = %d\n"
         "keep_after_death         = %d\n"
         "persist_physick_tears    = %d\n"
         "remember_per_weapon      = %d\n"
         "remember_across_sessions = %d\n"
         "log_effects              = %d\n"
         "log_untracked            = %d\n"
         "force_persist_ids        = %zu id(s)\n"
         "never_persist_ids        = %zu id(s)",
         g_keep_fast_travel, g_keep_death, g_persist_physick,
         g_weapon_memory, g_session_persist,
         g_log_effects, g_log_untracked,
         g_force_persist.size(), g_never_persist.size());
}

