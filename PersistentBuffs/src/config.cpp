// Options that USED to exist -- removed with a specific reason in the log
// (anything else unknown is removed as plain "unknown").
struct DeprecatedKey { const char* section; const char* key; const char* why; };
const DeprecatedKey kDeprecated[] = {
    { "persistence", "restore_remaining_time",
      "buffs now ALWAYS restore with their remaining time" },
    { "persistence", "restore_buff_power",
      "re-applied buffs now ALWAYS keep their cast-time power" },
    { "persistence", "exclude_ids",
      "replaced by the source allowlist + never_persist_ids" },
    { "persistence", "persist_great_runes",
      "Great Rune persistence was removed (did not work as intended)" },
    { "persistence", "always_persist_ids",
      "the AoW self-buff list is built in now" },
    { "persistence", "reapply_delay_ms",
      "hard-coded (500 ms tuned value)" },
};

const SchemaKey* schema_find(const std::string& sec, const std::string& key) {
    for (const auto& k : kSchema)
        if (sec == k.section && key == k.key) return &k;
    return nullptr;
}

const char* deprecated_why(const std::string& sec, const std::string& key) {
    for (const auto& d : kDeprecated)
        if (sec == d.section && key == d.key) return d.why;
    return nullptr;
}

bool schema_def_bool(const char* section, const char* key) {
    const SchemaKey* k = schema_find(section, key);
    return k && std::strcmp(k->def, "1") == 0;
}

// Rewrite the .ini from the schema, preserving user values for known options.
// Returns true if the file was (re)written.
bool heal_config(const Ini& ini, bool file_existed) {
    std::vector<const SchemaKey*> missing;
    for (const auto& k : kSchema)
        if (!ini.has(k.section, k.key)) missing.push_back(&k);

    std::vector<std::pair<std::string, std::string>> extra; // (section, key)
    for (const auto& sec : ini.section_names())
        for (const auto& key : ini.keys_in(sec))
            if (!schema_find(sec, key)) extra.emplace_back(sec, key);

    if (file_existed && missing.empty() && extra.empty()) return false;

    std::ofstream f(config_path());
    if (!f) {
        flog("[WARN] config: .ini needs healing but the file is not writable");
        return false;
    }

    f << "; ============================================================\n";
    f << ";  PersistentBuffs v" << kModVersion << " -- configuration\n";
    f << ";  This file is auto-healed on every game start: missing options\n";
    f << ";  come back with their defaults, unknown options are removed,\n";
    f << ";  your values for known options are kept.\n";
    f << "; ============================================================\n";

    const char* cur_section = "";
    for (const auto& k : kSchema) {
        if (std::strcmp(cur_section, k.section) != 0) {
            cur_section = k.section;
            f << "\n[" << k.section << "]\n";
        }
        f << "\n";
        // comment block: one "; " prefix per line
        const char* c = k.comment;
        while (*c) {
            const char* nl = std::strchr(c, '\n');
            const size_t n = nl ? static_cast<size_t>(nl - c) : std::strlen(c);
            f << "; " << std::string(c, n) << "\n";
            c += n + (nl ? 1 : 0);
        }
        const std::string val = ini.has(k.section, k.key)
                                    ? ini.get_string(k.section, k.key)
                                    : std::string(k.def);
        f << k.key << " = " << val << "\n";
    }

    if (!file_existed) {
        flog("config: no .ini found -- wrote a fresh one with defaults");
        return true;
    }
    for (const auto* k : missing)
        flog("config: healed .ini -- added missing [%s] %s = %s (default)",
             k->section, k->key, *k->def ? k->def : "<empty>");
    for (const auto& [sec, key] : extra) {
        const char* why = deprecated_why(sec, key);
        if (why) flog("config: healed .ini -- removed deprecated [%s] %s (%s)",
                      sec.c_str(), key.c_str(), why);
        else     flog("config: healed .ini -- removed unknown [%s] %s",
                      sec.c_str(), key.c_str());
    }
    return true;
}

