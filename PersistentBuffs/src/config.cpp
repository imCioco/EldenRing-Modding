// Parse a Paramdex names blob: lines of "<id> <name>" (UTF-8; BOM or malformed
// lines are skipped). Entries overwrite existing map entries when `overlay`.
void parse_names_blob(const unsigned char* data, size_t len,
                      std::unordered_map<int, std::string>& out, bool overlay) {
    const char* p   = reinterpret_cast<const char*>(data);
    const char* end = p + len;
    while (p < end) {
        const char* eol = p;
        while (eol < end && *eol != '\n') ++eol;
        const char* q = p;
        long id = 0;
        bool has_id = false;
        while (q < eol && *q >= '0' && *q <= '9') {
            id = id * 10 + (*q - '0');
            ++q;
            has_id = true;
        }
        if (has_id && q < eol && (*q == ' ' || *q == '\t')) {
            while (q < eol && (*q == ' ' || *q == '\t')) ++q;
            const char* e = eol;
            while (e > q && (e[-1] == '\r' || e[-1] == ' ' || e[-1] == '\t')) --e;
            if (e > q) {
                if (overlay) out[static_cast<int>(id)] = std::string(q, e);
                else         out.emplace(static_cast<int>(id), std::string(q, e));
            }
        }
        p = eol + 1;
    }
}

// ---- .ini schema + auto-heal --------------------------------------------
// The DLL owns the canonical option list. On every start the loaded .ini is
// compared against it: missing options are re-added with their defaults,
// unknown/deprecated options are removed, and user values for known options
// are preserved verbatim. The file is rewritten ONLY when its option set
// differs from the schema, so hand-edited comments survive normal runs.

struct SchemaKey {
    const char* section;
    const char* key;
    const char* def;     // default, exactly as written into the .ini
    const char* comment; // '\n'-separated comment lines (without the "; ")
};

